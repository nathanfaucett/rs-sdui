use std::{
    collections::BTreeMap,
    env,
    error::Error,
    fs,
    path::{Path, PathBuf},
};

use proc_macro2::{Ident, Span, TokenStream};
use quote::quote;
use serde_json::Value;

#[derive(Clone, Debug)]
pub struct Catalog {
    module: String,
    path: PathBuf,
}

impl Catalog {
    #[must_use]
    pub fn new(module: impl Into<String>, path: impl Into<PathBuf>) -> Self {
        Self {
            module: module.into(),
            path: path.into(),
        }
    }
}

/// Generates `a2ui_catalogs.rs` in Cargo's `OUT_DIR`.
///
/// # Errors
///
/// Returns an error when a catalog cannot be read, parsed, or rendered, or when the output cannot be written.
pub fn generate(catalogs: &[Catalog]) -> Result<(), Box<dyn Error>> {
    let output = env::var_os("OUT_DIR").ok_or("OUT_DIR is only available from build.rs")?;
    let source = generate_source(catalogs)?;
    fs::write(Path::new(&output).join("a2ui_catalogs.rs"), source)?;
    Ok(())
}

/// Generates Rust source without writing it. This is useful for custom build tools.
///
/// # Errors
///
/// Returns an error when a catalog cannot be read, parsed, or rendered.
pub fn generate_source(catalogs: &[Catalog]) -> Result<String, Box<dyn Error>> {
    let mut generated = TokenStream::new();

    for catalog in catalogs {
        println!("cargo:rerun-if-changed={}", catalog.path.display());
        let input = fs::read_to_string(&catalog.path).map_err(|error| {
            format!("failed to read catalog {}: {error}", catalog.path.display())
        })?;
        let document: Value = serde_json::from_str(&input).map_err(|error| {
            format!(
                "failed to parse catalog {}: {error}",
                catalog.path.display()
            )
        })?;
        generated.extend(render_catalog(&catalog.module, &document)?);
    }

    let syntax = syn::parse_file(&generated.to_string())?;
    Ok(format!(
        "// @generated by a2ui-codegen. Do not edit.\n{}",
        prettyplease::unparse(&syntax)
    ))
}

fn render_catalog(module: &str, document: &Value) -> Result<TokenStream, Box<dyn Error>> {
    let module = parse_ident(module)?;
    let protocol = document
        .get("protocolVersion")
        .and_then(Value::as_str)
        .ok_or("catalog protocolVersion is required")?;
    if protocol != "1.0" {
        return Err(format!("only A2UI v1.0 catalogs are supported, found {protocol}").into());
    }
    let catalog_id = document
        .get("catalogId")
        .and_then(Value::as_str)
        .ok_or("catalog catalogId is required")?;

    let mut components = Vec::new();
    if let Some(entries) = document.get("components").and_then(Value::as_object) {
        for (name, schema) in entries {
            components.push(render_component(name, schema, document)?);
        }
    }

    let mut functions = Vec::new();
    if let Some(entries) = document.get("functions").and_then(Value::as_object) {
        for (name, schema) in entries {
            functions.push(render_function(name, schema)?);
        }
    }

    Ok(quote! {
        pub mod #module {
            pub const CATALOG_ID: &str = #catalog_id;

            #[must_use]
            pub fn surface(
                surface_id: impl Into<String>,
            ) -> ::a2ui::CreateSurface {
                ::a2ui::CreateSurface::new(surface_id, CATALOG_ID)
            }

            #(#components)*

            pub mod functions {
                #(#functions)*
            }
        }
    })
}

#[derive(Default)]
struct FlatSchema {
    properties: BTreeMap<String, Value>,
    required: Vec<String>,
    description: Option<String>,
    checkable: bool,
}

fn flatten_schema(
    schema: &Value,
    document: &Value,
    flat: &mut FlatSchema,
    depth: usize,
) -> Result<(), Box<dyn Error>> {
    if depth > 32 {
        return Err("catalog schema reference depth exceeds 32".into());
    }

    if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
        if reference.ends_with("/Checkable") {
            flat.checkable = true;
            return Ok(());
        }
        if let Some(pointer) = reference.strip_prefix('#') {
            let target = document
                .pointer(pointer)
                .ok_or_else(|| format!("unresolved catalog reference {reference}"))?;
            return flatten_schema(target, document, flat, depth + 1);
        }
        return Ok(());
    }

    if flat.description.is_none() {
        flat.description = schema
            .get("description")
            .and_then(Value::as_str)
            .map(str::to_owned);
    }
    if let Some(properties) = schema.get("properties").and_then(Value::as_object) {
        for (name, schema) in properties {
            flat.properties.insert(name.clone(), schema.clone());
        }
    }
    if let Some(required) = schema.get("required").and_then(Value::as_array) {
        for name in required.iter().filter_map(Value::as_str) {
            if !flat.required.iter().any(|item| item == name) {
                flat.required.push(name.to_owned());
            }
        }
    }
    if let Some(branches) = schema.get("allOf").and_then(Value::as_array) {
        for branch in branches {
            flatten_schema(branch, document, flat, depth + 1)?;
        }
    }
    Ok(())
}

#[derive(Clone)]
enum PropertyKind {
    DynamicString,
    DynamicNumber,
    DynamicBoolean,
    DynamicStringList,
    DynamicValue,
    ChildList,
    Child,
    Action,
    FunctionCall,
    DataBinding,
    String,
    Number,
    Integer,
    Boolean,
    Json,
    Enum(Ident),
}

struct Property {
    wire_name: String,
    rust_name: Ident,
    kind: PropertyKind,
    definition: TokenStream,
    docs: TokenStream,
}

#[allow(
    clippy::too_many_lines,
    reason = "builder assembly stays in one module"
)]
fn render_component(
    name: &str,
    schema: &Value,
    document: &Value,
) -> Result<TokenStream, Box<dyn Error>> {
    let builder = type_ident(name)?;
    let docs = doc_attributes(schema.get("description").and_then(Value::as_str));
    let mut flat = FlatSchema::default();
    flatten_schema(schema, document, &mut flat, 0)?;

    let mut properties = Vec::new();
    for (property_name, property_schema) in &flat.properties {
        if matches!(property_name.as_str(), "component" | "id") {
            continue;
        }
        properties.push(render_property(&builder, property_name, property_schema)?);
    }

    let required = flat
        .required
        .iter()
        .filter(|required_name| **required_name != "component")
        .filter_map(|required_name| {
            properties
                .iter()
                .find(|property| property.wire_name == *required_name)
        })
        .collect::<Vec<_>>();
    let optional = properties
        .iter()
        .filter(|property| {
            !flat
                .required
                .iter()
                .any(|required_name| required_name == &property.wire_name)
        })
        .collect::<Vec<_>>();

    let parameters = required.iter().map(|property| {
        let name = &property.rust_name;
        let input = input_type(&property.kind);
        quote!(#name: #input)
    });
    let required_setters = required.iter().map(|property| {
        let wire_name = &property.wire_name;
        let rust_name = &property.rust_name;
        match &property.kind {
            PropertyKind::Child => quote! {
                let element = element.child(#wire_name, #rust_name);
            },
            PropertyKind::ChildList => quote! {
                let element = element.children(#wire_name, #rust_name);
            },
            PropertyKind::Action => quote! {
                let element = element.action(#wire_name, #rust_name);
            },
            _ => {
                let value = input_value(&property.kind, rust_name);
                quote! {
                    let element = element.property(#wire_name, #value);
                }
            }
        }
    });
    let optional_setters = optional.iter().map(|property| {
        let wire_name = &property.wire_name;
        let rust_name = &property.rust_name;
        let input = input_type(&property.kind);
        let value = input_value(&property.kind, rust_name);
        let docs = &property.docs;
        match &property.kind {
            PropertyKind::Child => quote! {
                #docs
                pub fn #rust_name(mut self, #rust_name: #input) -> Self {
                    self.0 = self.0.child(#wire_name, #rust_name);
                    self
                }
            },
            PropertyKind::ChildList => quote! {
                #docs
                pub fn #rust_name(mut self, #rust_name: #input) -> Self {
                    self.0 = self.0.children(#wire_name, #rust_name);
                    self
                }
            },
            PropertyKind::Action => quote! {
                #docs
                pub fn #rust_name(mut self, #rust_name: #input) -> Self {
                    self.0 = self.0.action(#wire_name, #rust_name);
                    self
                }
            },
            _ => quote! {
                #docs
                pub fn #rust_name(mut self, #rust_name: #input) -> Self {
                    self.0 = self.0.property(#wire_name, #value);
                    self
                }
            },
        }
    });
    let definitions = properties.iter().map(|property| &property.definition);
    let default_impl = required.is_empty().then(|| {
        quote! {
            impl Default for #builder {
                fn default() -> Self {
                    Self::new()
                }
            }
        }
    });
    let check_setter = flat.checkable.then(|| {
        quote! {
            pub fn checks(
                mut self,
                checks: impl IntoIterator<Item = ::a2ui::CheckRule>,
            ) -> Self {
                let checks = checks
                    .into_iter()
                    .map(::serde_json::Value::from)
                    .collect::<Vec<_>>();
                self.0 = self.0.property("@checks", ::serde_json::Value::Array(checks));
                self
            }
        }
    });

    Ok(quote! {
        #(#definitions)*
        #docs
        #[derive(Debug)]
        #[must_use]
        pub struct #builder(::a2ui::Element);

        impl #builder {
            pub fn new(
                #(#parameters),*
            ) -> Self {
                let element = ::a2ui::Element::new(
                    ::a2ui::Component::new("", #name)
                );
                #(#required_setters)*
                Self(element)
            }

            pub fn catalog_id(mut self, catalog_id: impl Into<String>) -> Self {
                self.0 = self.0.property("@catalogId", catalog_id.into());
                self
            }

            #(#optional_setters)*
            #check_setter
        }

        impl From<#builder> for ::a2ui::Element {
            fn from(value: #builder) -> Self {
                value.0
            }
        }

        #default_impl
    })
}

fn render_property(
    builder: &Ident,
    name: &str,
    schema: &Value,
) -> Result<Property, Box<dyn Error>> {
    let rust_name = value_ident(name)?;
    let docs = doc_attributes(schema.get("description").and_then(Value::as_str));
    let mut definition = TokenStream::new();
    let kind = if let Some(values) = string_enum(schema) {
        let enum_name = type_ident(&format!("{builder}{}", pascal_case(name)))?;
        definition = render_enum(&enum_name, &values)?;
        PropertyKind::Enum(enum_name)
    } else {
        property_kind(schema)
    };

    Ok(Property {
        wire_name: name.to_owned(),
        rust_name,
        kind,
        definition,
        docs,
    })
}

fn render_enum(name: &Ident, values: &[String]) -> Result<TokenStream, Box<dyn Error>> {
    let variants = values
        .iter()
        .map(|value| Ok((type_ident(value)?, value)))
        .collect::<Result<Vec<_>, Box<dyn Error>>>()?;
    let variant_idents = variants.iter().map(|(ident, _)| ident);
    let arms = variants
        .iter()
        .map(|(ident, value)| quote!(Self::#ident => #value));

    Ok(quote! {
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        pub enum #name {
            #(#variant_idents),*
        }

        impl #name {
            #[must_use]
            pub const fn as_str(self) -> &'static str {
                match self {
                    #(#arms),*
                }
            }
        }

        impl From<#name> for ::serde_json::Value {
            fn from(value: #name) -> Self {
                Self::String(value.as_str().to_owned())
            }
        }
    })
}

#[allow(
    clippy::too_many_lines,
    reason = "function builder assembly stays in one module"
)]
fn render_function(name: &str, schema: &Value) -> Result<TokenStream, Box<dyn Error>> {
    let function_name = value_ident(name)?;
    let builder = type_ident(&format!("{name}Function"))?;
    let property_prefix = type_ident(name)?;
    let docs = doc_attributes(schema.get("description").and_then(Value::as_str));
    let empty = serde_json::Map::new();
    let args = schema
        .get("properties")
        .and_then(|properties| properties.get("args"))
        .and_then(Value::as_object)
        .unwrap_or(&empty);
    let properties = args
        .get("properties")
        .and_then(Value::as_object)
        .cloned()
        .unwrap_or_default();
    let required = args
        .get("required")
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_default()
        .iter()
        .filter_map(Value::as_str)
        .map(str::to_owned)
        .collect::<Vec<_>>();

    let mut inputs = Vec::new();
    let mut optional = Vec::new();
    let mut definitions = Vec::new();
    for (argument_name, argument_schema) in &properties {
        let property = render_property(&property_prefix, argument_name, argument_schema)?;
        definitions.push(property.definition.clone());
        if required
            .iter()
            .any(|required_name| required_name == argument_name)
        {
            inputs.push(property);
        } else {
            optional.push(property);
        }
    }
    let parameters = inputs.iter().map(|property| {
        let rust_name = &property.rust_name;
        let input = input_type(&property.kind);
        quote!(#rust_name: #input)
    });
    let setters = inputs.iter().map(|property| {
        let wire_name = &property.wire_name;
        let rust_name = &property.rust_name;
        let value = input_value(&property.kind, rust_name);
        quote!(.arg(#wire_name, #value))
    });
    let optional_setters = optional.iter().map(|property| {
        let wire_name = &property.wire_name;
        let rust_name = &property.rust_name;
        let input = input_type(&property.kind);
        let value = input_value(&property.kind, rust_name);
        let docs = &property.docs;
        quote! {
            #docs
            pub fn #rust_name(mut self, #rust_name: #input) -> Self {
                self.0 = self.0.arg(#wire_name, #value);
                self
            }
        }
    });

    let agent_only = schema.get("allowedCallers").and_then(Value::as_str) == Some("agentOnly");
    let requires_user_activation = schema
        .get("requiresUserActivation")
        .and_then(Value::as_bool)
        .unwrap_or(false);
    let dynamic_types = match schema.get("returnType").and_then(Value::as_str) {
        Some("string") => vec![quote!(::a2ui::DynamicString), quote!(::a2ui::DynamicValue)],
        Some("number") => vec![quote!(::a2ui::DynamicNumber), quote!(::a2ui::DynamicValue)],
        Some("boolean" | "validationResult") => vec![
            quote!(::a2ui::DynamicBoolean),
            quote!(::a2ui::DynamicValue),
            quote!(::a2ui::Condition),
        ],
        Some("array" | "object" | "any") => vec![quote!(::a2ui::DynamicValue)],
        _ => Vec::new(),
    };
    let dynamic_conversions = if agent_only || requires_user_activation {
        Vec::new()
    } else {
        dynamic_types
            .iter()
            .map(|target| {
                quote! {
                    impl From<#builder> for #target {
                        fn from(value: #builder) -> Self {
                            ::a2ui::FunctionCall::from(value).into()
                        }
                    }
                }
            })
            .collect()
    };
    let view_action_conversion = (!agent_only).then(|| {
        quote! {
            impl From<#builder> for ::a2ui::ViewAction {
                fn from(value: #builder) -> Self {
                    ::a2ui::FunctionCall::from(value).into()
                }
            }
        }
    });

    Ok(quote! {
        #(#definitions)*
        #docs
        #[derive(Debug)]
        #[must_use]
        pub struct #builder(::a2ui::FunctionCall);

        impl #builder {
            #(#optional_setters)*
        }

        #docs
        pub fn #function_name(#(#parameters),*) -> #builder {
            #builder(
                ::a2ui::FunctionCall::new(#name)
                    .catalog_id(super::CATALOG_ID)
                    #(#setters)*
            )
        }

        impl From<#builder> for ::a2ui::FunctionCall {
            fn from(value: #builder) -> Self {
                value.0
            }
        }

        #(#dynamic_conversions)*
        #view_action_conversion
    })
}

fn property_kind(schema: &Value) -> PropertyKind {
    if let Some(reference) = reference_name(schema) {
        return match reference {
            "DynamicString" => PropertyKind::DynamicString,
            "DynamicNumber" => PropertyKind::DynamicNumber,
            "DynamicBoolean" => PropertyKind::DynamicBoolean,
            "DynamicStringList" => PropertyKind::DynamicStringList,
            "DynamicValue" => PropertyKind::DynamicValue,
            "ChildList" => PropertyKind::ChildList,
            "Child" | "ComponentId" => PropertyKind::Child,
            "Action" => PropertyKind::Action,
            "FunctionCall" => PropertyKind::FunctionCall,
            "DataBinding" => PropertyKind::DataBinding,

            _ => PropertyKind::Json,
        };
    }

    if let Some(branches) = schema.get("oneOf").and_then(Value::as_array) {
        let has_binding = branches
            .iter()
            .any(|branch| reference_name(branch) == Some("DataBinding"));
        let has_call = branches
            .iter()
            .any(|branch| reference_name(branch) == Some("FunctionCall"));
        if has_binding && has_call && branches.len() == 2 {
            return PropertyKind::DynamicValue;
        }
        if has_binding
            && branches
                .iter()
                .any(|branch| branch.get("type").and_then(Value::as_str) == Some("string"))
        {
            return PropertyKind::DynamicString;
        }
    }

    match schema.get("type").and_then(Value::as_str) {
        Some("string") => PropertyKind::String,
        Some("number") => PropertyKind::Number,
        Some("integer") => PropertyKind::Integer,
        Some("boolean") => PropertyKind::Boolean,
        Some("array" | "object") => PropertyKind::Json,
        _ if schema.get("description").is_some() && schema.get("type").is_none() => {
            PropertyKind::DynamicValue
        }
        _ => PropertyKind::Json,
    }
}

fn reference_name(schema: &Value) -> Option<&str> {
    if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
        return reference.rsplit('/').next();
    }
    schema
        .get("allOf")
        .and_then(Value::as_array)
        .and_then(|branches| branches.iter().find_map(reference_name))
}

fn string_enum(schema: &Value) -> Option<Vec<String>> {
    if schema.get("type").and_then(Value::as_str) != Some("string") {
        return None;
    }
    schema.get("enum").and_then(Value::as_array).map(|values| {
        values
            .iter()
            .filter_map(Value::as_str)
            .map(str::to_owned)
            .collect()
    })
}

fn input_type(kind: &PropertyKind) -> TokenStream {
    match kind {
        PropertyKind::DynamicString => quote!(impl Into<::a2ui::DynamicString>),
        PropertyKind::DynamicNumber => quote!(impl Into<::a2ui::DynamicNumber>),
        PropertyKind::DynamicBoolean => quote!(impl Into<::a2ui::DynamicBoolean>),
        PropertyKind::DynamicStringList => quote!(impl Into<::a2ui::DynamicStringList>),
        PropertyKind::DynamicValue => quote!(impl Into<::a2ui::DynamicValue>),
        PropertyKind::ChildList => quote!(impl ::a2ui::IntoChildren),
        PropertyKind::Child => quote!(impl Into<::a2ui::Element>),
        PropertyKind::Action => quote!(impl Into<::a2ui::ViewAction>),
        PropertyKind::FunctionCall => quote!(impl Into<::a2ui::FunctionCall>),
        PropertyKind::DataBinding => quote!(impl Into<::a2ui::DataBinding>),
        PropertyKind::String => quote!(impl Into<String>),
        PropertyKind::Number => quote!(f64),
        PropertyKind::Integer => quote!(i64),
        PropertyKind::Boolean => quote!(bool),
        PropertyKind::Json => quote!(::serde_json::Value),
        PropertyKind::Enum(name) => quote!(#name),
    }
}

fn input_value(kind: &PropertyKind, name: &Ident) -> TokenStream {
    match kind {
        PropertyKind::DynamicString => {
            quote!(::serde_json::Value::from(Into::<::a2ui::DynamicString>::into(#name)))
        }
        PropertyKind::DynamicNumber => {
            quote!(::serde_json::Value::from(Into::<::a2ui::DynamicNumber>::into(#name)))
        }
        PropertyKind::DynamicBoolean => {
            quote!(::serde_json::Value::from(Into::<::a2ui::DynamicBoolean>::into(#name)))
        }
        PropertyKind::DynamicStringList => {
            quote!(::serde_json::Value::from(Into::<::a2ui::DynamicStringList>::into(#name)))
        }
        PropertyKind::DynamicValue => {
            quote!(::serde_json::Value::from(Into::<::a2ui::DynamicValue>::into(#name)))
        }
        PropertyKind::ChildList => {
            quote!(::serde_json::Value::from(Into::<::a2ui::ChildList>::into(#name)))
        }
        PropertyKind::Child => {
            quote!(::serde_json::Value::String(Into::<String>::into(#name)))
        }
        PropertyKind::Action => {
            quote!(::serde_json::Value::from(Into::<::a2ui::Action>::into(#name)))
        }
        PropertyKind::FunctionCall => {
            quote!(::serde_json::Value::from(Into::<::a2ui::FunctionCall>::into(#name)))
        }
        PropertyKind::DataBinding => {
            quote!(::serde_json::Value::from(Into::<::a2ui::DataBinding>::into(#name)))
        }
        PropertyKind::String => quote!(::serde_json::Value::String(Into::<String>::into(#name))),
        PropertyKind::Number => {
            quote!(::serde_json::Value::from(::a2ui::number(#name)))
        }
        PropertyKind::Integer | PropertyKind::Boolean | PropertyKind::Enum(_) => {
            quote!(::serde_json::Value::from(#name))
        }
        PropertyKind::Json => quote!(#name),
    }
}

fn doc_attributes(description: Option<&str>) -> TokenStream {
    description.map_or_else(
        TokenStream::new,
        |description| quote!(#[doc = #description]),
    )
}

fn parse_ident(value: &str) -> Result<Ident, Box<dyn Error>> {
    syn::parse_str(value)
        .map_err(|error| format!("invalid Rust identifier {value}: {error}").into())
}

fn value_ident(value: &str) -> Result<Ident, Box<dyn Error>> {
    ident_or_raw(&snake_case(value))
}

fn type_ident(value: &str) -> Result<Ident, Box<dyn Error>> {
    ident_or_raw(&pascal_case(value))
}

fn ident_or_raw(value: &str) -> Result<Ident, Box<dyn Error>> {
    if value.is_empty() {
        return Err("catalog names must contain an identifier character".into());
    }
    if matches!(value, "self" | "Self" | "super" | "crate") {
        return parse_ident(&format!("{value}_"));
    }
    if KEYWORDS.contains(&value) {
        return Ok(Ident::new_raw(value, Span::call_site()));
    }
    parse_ident(value)
}

const KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern", "false",
    "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref",
    "return", "static", "struct", "trait", "true", "type", "unsafe", "use", "where", "while",
    "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof", "unsized",
    "virtual", "yield", "try", "gen",
];

fn snake_case(value: &str) -> String {
    let mut output = String::new();
    let mut previous_is_lowercase = false;
    for character in value.chars() {
        if !character.is_alphanumeric() {
            output.push('_');
            previous_is_lowercase = false;
            continue;
        }
        if character.is_uppercase() && previous_is_lowercase {
            output.push('_');
        }
        output.extend(character.to_lowercase());
        previous_is_lowercase = character.is_lowercase() || character.is_numeric();
    }
    output
}

fn pascal_case(value: &str) -> String {
    let mut output = String::new();
    for part in snake_case(value).split('_').filter(|part| !part.is_empty()) {
        let mut characters = part.chars();
        if let Some(first) = characters.next() {
            output.extend(first.to_uppercase());
            output.push_str(characters.as_str());
        }
    }
    output
}

